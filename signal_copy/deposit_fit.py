# -*- coding: utf-8 -*-
"""Влезает ли сигнал в депозит при минимальном лоте 0.01?"""
C = {"XAUUSD":100, "AUDUSD":100_000}
S = [("AUDUSD","BUY",0.70820,0.70669,0.71295),
     ("XAUUSD","BUY",4398,4377,4436.2),
     ("XAUUSD","SELL",4399,4416.7,4366.8),
     ("AUDUSD","SELL",0.70580,0.70689,0.70392)]
MIN_LOT = 0.01
print(f"{'сигнал':<15}{'риск/0.01 лот':>14}{'от $500':>10}{'от $1000':>10}   {'R до TP4':>8}  вердикт при $500")
print("─"*88)
for sym, side, entry, sl, tp4 in S:
    risk_usd = MIN_LOT * abs(entry-sl) * C[sym]
    r4 = abs(tp4-entry)/abs(entry-sl)
    p500, p1000 = risk_usd/500*100, risk_usd/1000*100
    ok = "влезает" if p500 <= 2.0 else "НЕ ВЛЕЗАЕТ — риск выше 2%"
    print(f"{sym+' '+side:<15}{risk_usd:>13,.2f}${p500:>9.2f}%{p1000:>9.2f}%   {r4:>8.2f}  {ok}")
print("""
Депозит для расчёта риска берём $500 (свои), а не $1000: бонусные деньги платформы
обычно нельзя вывести, и считать процент риска от них — значит рисковать больше,
чем кажется.

Винрейт, нужный чтобы не терять, если брать только TP4:""")
for sym, side, entry, sl, tp4 in S:
    r4 = abs(tp4-entry)/abs(entry-sl)
    print(f"  {sym} {side:<5} R={r4:.2f} → {100/(1+r4):.0f}%")
