"""Price-free owner proposal; one post-GO capture and immutable IOC plan.

No network, account writer, order permission or research authority here. Reuse
the existing venue sizing, cost, funding and native-guard compiler unchanged.
"""
import copy
from pathlib import Path

from bot.kity_m3_orders_off import digest
from research_lab.kity_execution_micro_runtime_v1 import BASKET, _owner_bounds
from research_lab.kity_micro_physical_owner_v1 import publish
from research_lab.kity_micro_pricing_intent_v2 import (
    _clock, _sha, make_intent, materialize, load_source,
)
from research_lab.kity_micro_transport_v1 import SourceError

SCHEMA = 'KITY_EXECUTION_MICRO_POST_GO_POLICY_V1'
GO_PREFIX = 'GO KITY_EXECUTION_MICRO_POLICY_V1 '
QUANTITY_RULE = 'MINIMUM_APPROVED_ROUNDING_FRONTIER_FROM_SINGLE_POST_GO_CAPTURE'


def make_policy(*, created_ms, valid_until_ms, physical_config_sha256,
                predecessor_plan_id, bounds):
    _clock(created_ms); _clock(valid_until_ms)
    if not 0 < valid_until_ms - created_ms <= 86400000:
        raise SourceError('POLICY_SESSION_CLOCK')
    bounds = _owner_bounds(bounds)
    if bounds['schema'] != 'kity_execution_micro_owner_bounds_v3':
        raise SourceError('POLICY_V3_BOUNDS_REQUIRED')
    p = dict(schema=SCHEMA, purpose='EXECUTION_MICRO_LIVE',
        created_ms=created_ms, valid_until_ms=valid_until_ms,
        physical_config_sha256=_sha(physical_config_sha256),
        predecessor_plan_id=_sha(predecessor_plan_id), bounds=bounds,
        basket=[dict(symbol=s, side=side) for s,side in BASKET],
        quantity_rule=QUANTITY_RULE, collar_bps='50', dispatch_window_ms=60000,
        pricing_anchor='WORST_CONSUMED_DEPTH_PRICE_OF_FRESH_SIZED_QUANTITY',
        source_rule='ONE_POST_GO_CAPTURE_COMMON_CTS_MAX_2_SECONDS',
        orders_allowed=False, research_evidence_eligible=False,
        counts_toward_C1_C2_C3=False)
    p['policy_id'] = digest(p)
    return p


def validate_policy(policy):
    try:
        expected = make_policy(**{k:policy[k] for k in (
            'created_ms', 'valid_until_ms', 'physical_config_sha256',
            'predecessor_plan_id', 'bounds')})
        if policy != expected:
            raise SourceError('POLICY_PIN_OR_RULE_CONFLICT')
    except (KeyError, TypeError) as exc:
        raise SourceError('POLICY_SCHEMA') from exc
    return policy


def dispatch_window(policy, go_ms, at_ms):
    _clock(go_ms); _clock(at_ms)
    if not policy['created_ms'] <= go_ms <= at_ms < policy['valid_until_ms']:
        raise SourceError('POLICY_GO_SESSION_CLOCK')
    if at_ms >= go_ms + policy['dispatch_window_ms']:
        raise SourceError('POST_GO_DISPATCH_DEADLINE')


def compile_after_go(policy, fresh, captures, *, go_ms, now_ms):
    validate_policy(policy); dispatch_window(policy, go_ms, now_ms)
    if (type(fresh.get('observed_start_ms')) is not int
            or fresh['observed_start_ms'] < go_ms):
        raise SourceError('CAPTURE_PRECEDES_GO')
    if (fresh.get('physical_config_sha256') != policy['physical_config_sha256']
            or fresh['plan']['bounds'] != policy['bounds']):
        raise SourceError('POST_GO_SOURCE_CUSTODY_CONFLICT')
    # The input plan is generated by the unchanged preflight/rounding-frontier
    # builder from this capture. No old plan or old quantities are input here.
    derived = make_intent(fresh, at_ms=now_ms, collar_bps=policy['collar_bps'],
        ttl_ms=go_ms + policy['dispatch_window_ms'] - now_ms,
        predecessor_plan_id=policy['predecessor_plan_id'])
    out = materialize(derived, fresh, captures, now_ms=now_ms)
    out.update(post_go_policy=copy.deepcopy(policy), post_go_go_ms=go_ms,
        human_go_template=GO_PREFIX + policy['policy_id'],
        rounding_basis=QUANTITY_RULE, research_evidence_eligible=False,
        counts_toward_C1_C2_C3=False)
    return out


def consume_policy_once(store, policy, owner_go_text, go_ms, capture, *, clock):
    validate_policy(policy)
    if owner_go_text != GO_PREFIX + policy['policy_id']:
        raise SourceError('EXACT_POLICY_GO_REQUIRED')
    at = clock(); dispatch_window(policy, go_ms, at); store = Path(store)
    publish(store/'policy-claim.json', dict(policy_id=policy['policy_id'],
        owner_go_text=owner_go_text, go_ms=go_ms, accepted_ms=at))
    try:
        fresh, caps = capture()  # exactly once, including failure/late completion
        out = compile_after_go(policy, fresh, caps, go_ms=go_ms, now_ms=clock())
        publish(store/'materialized.json', out)
        return out
    except Exception as exc:
        publish(store/'no-send.json', dict(status='POST_GO_POLICY_NO_SEND',
            policy_id=policy['policy_id'], reason=type(exc).__name__+':'+str(exc)[:512],
            observed_ms=clock(), broker_writes=0))
        raise


def verify_compilation(dossier):
    policy = dossier['post_go_policy']; validate_policy(policy)
    plan = dossier['plan']
    fresh, caps = load_source(dossier['materialization_capture_path'],
        plan['captured_source_sha256'], policy['bounds'], policy['physical_config_sha256'])
    expected = compile_after_go(policy, fresh, caps,
        go_ms=dossier['post_go_go_ms'], now_ms=plan['pricing_intent']['materialized_ms'])
    if dossier != expected:
        raise SourceError('POST_GO_DERIVED_PLAN_REPLAY_CONFLICT')
